'use strict';
// Pull request body: chosen and rejected stories with scores and reasons, the
// claim-check table, lint results, the social pack inline, preview note.

const { articleUrl } = require('./build');

function table(headers, rows) {
  const esc = v => String(v == null ? '' : v).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
  return [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...rows.map(r => `| ${r.map(esc).join(' | ')} |`)].join('\n');
}

function prBody(cfg, ctx) {
  const { rec, choice, ranked, rejected, dropped, claims, revisions, lintResult, socialMd, snapshot, research } = ctx;
  const f = cfg.formats[rec.format];
  const unsupported = claims.filter(c => !c.supported);
  const parts = [];

  parts.push(`## ${cfg.seriesName}, issue ${rec.issue}: ${rec.title}`);
  parts.push(`Format **${rec.format}, ${f.name}**. Reason: ${choice.reason}.`);
  parts.push(`Snapshot \`content/news-snapshots/${snapshot.date}.json\`: ${snapshot.count} items in the last ${snapshot.windowDays} days (${snapshot.totalInFeed} in the feed, via ${snapshot.via}).`);
  parts.push(`Page: \`blog/${rec.year}/${rec.slug}.html\` (${articleUrl(cfg, rec)} once merged). Azure Static Web Apps will comment the preview URL on this pull request when its build finishes.`);
  parts.push(`Review checklist: read the article on the preview, check every claim against the sources listed on the page, then merge to publish. Merging triggers the deploy and the social pack email. Closing without merging publishes nothing.`);

  parts.push('## Why this matters');
  parts.push(rec.whyThisMatters.map(b => `- ${b}`).join('\n'));

  parts.push('## Stories chosen');
  parts.push(table(['Score', 'Rules', 'Source', 'Title', 'Reason'],
    ranked.filter(r => ctx.chosenLinks.has(r.link)).map(r => [r.finalScore, r.rulesScore, r.source, `[${r.title}](${r.link})`, r.modelReason || ''])));

  parts.push('## Stories ranked but not used');
  parts.push(rejected.length
    ? table(['Score', 'Rules', 'Source', 'Title', 'Reason'], rejected.map(r => [r.finalScore, r.rulesScore, r.source, `[${r.title}](${r.link})`, r.modelReason || '']))
    : '_None._');

  parts.push(`## Dropped by the rules pass (below threshold ${cfg.scoring.threshold}, or already covered)`);
  parts.push(dropped.length ? dropped.slice(0, 40).map(d => `- ${d.rulesScore} ${d.source}: ${d.title}`).join('\n') + (dropped.length > 40 ? `\n- and ${dropped.length - 40} more` : '') : '_None._');

  parts.push('## Research');
  parts.push(research.map(r => `- ${r.fetched ? 'Fetched' : 'Summary only'}: [${r.title}](${r.link})${r.note ? ` (${r.note})` : ''}`).join('\n'));

  parts.push(`## Claim check (${claims.length} claims, ${unsupported.length} unsupported${revisions ? `, after ${revisions} revision pass${revisions > 1 ? 'es' : ''}` : ''})`);
  if (unsupported.length) {
    parts.push(`> **${unsupported.length} claim${unsupported.length > 1 ? 's remain' : ' remains'} unsupported by the fetched sources. Check before merging.**`);
  }
  parts.push(table(['Supported', 'Claim', 'Source', 'Evidence'],
    claims.sort((a, b) => Number(a.supported) - Number(b.supported)).map(c => [c.supported ? 'yes' : '**NO**', c.claim, c.sourceUrl || '', c.evidence])));

  parts.push('## Lint');
  parts.push(lintResult.length ? lintResult.map(p => `- ${p}`).join('\n') : 'All deterministic checks passed (em dash, banned names, UK spelling, lengths, source links, product mentions, prices, hype words).');

  parts.push('## Sources listed on the page');
  parts.push(rec.sources.map(s => `- [${s.title}](${s.url}), ${s.publisher} (${s.type})`).join('\n'));

  parts.push('## Social pack');
  parts.push(`Also saved at \`content/social-packs/${rec.slug}.md\`. Sent to the distribution list automatically when this pull request is merged.`);
  parts.push(socialMd.replace(/^# .*\n/, '').replace(/^## /gm, '### '));

  parts.push('---');
  parts.push('Generated by the fortnightly editor (tools/blog). A human reviews and approves every article before it goes live.');
  return parts.join('\n\n');
}

module.exports = { prBody, table };
